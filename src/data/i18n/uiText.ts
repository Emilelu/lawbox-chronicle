/** 键集快照（测试与调试用；顺序即简中键源顺序） */
export const UI_TEXT_KEYS: readonly UiTextKey[] = Object.keys(ZH_HANS_UI) as UiTextKey[];

/** 运行期键判别（动态 key 场景：bus 的 messageKey → UI 文案） */
export function isUiTextKey(key: string): key is UiTextKey {
  return Object.prototype.hasOwnProperty.call(ZH_HANS_UI, key);
}

/**
 * 取文案：locale → 简中 → key 本身（三级回落，绝不 undefined）。
 * {name} 形式的占位符经 vars 插值；缺参占位原样保留，便于发现漏传。
 */
export function tUi(
  locale: LocaleId,
  key: UiTextKey,
  vars?: Readonly<Record<string, string | number>>,
): string {
  const raw = UI_TEXT[locale][key] ?? UI_TEXT['zh-Hans'][key] ?? key;
  if (vars === undefined) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : match,
  );
}

/** 遗产句中的 <br> 清洗（legacy.congratulations 原文含 <br>，按原样搬运、此处净化） */
export function stripBr(text: string): string {
  return text.replace(/<br\s*\/?>/gi, '\n');
}

/** 概率数字格式化：0.06 → '6%'、0.2605 → '26.05%'（概率公示统一走这里） */
export function formatPercent(rate: number): string {
  const pct = rate * 100;
  const rounded = Math.round(pct * 100) / 100;
  return `${rounded}%`;
}

