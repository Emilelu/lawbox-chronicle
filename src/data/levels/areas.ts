import type { TerrainCell, Vec2 } from '../../core/types';
import type { Level3D, HeightMap } from '../../engine/puzzle/grid';

const g = (rows: number[][]): TerrainCell[][] =>
  rows.map((row) => row.map((v) => v as TerrainCell));

/** 全 0 海拔层 */
const flat = (w: number, h: number): number[][] =>
  Array.from({ length: h }, () => Array.from({ length: w }, () => 0));

/** 把若干格抬到 level 海拔（构造期辅助，产出后只读使用） */
const raise = (heights: number[][], cells: readonly Vec2[], level: number): number[][] => {
  for (const c of cells) {
    const row = heights[c.y];
    if (row !== undefined) row[c.x] = level;
  }
  return heights;
};

/** 环绕 (cx,cy) 的 8 邻格 */
const ring8 = (cx: number, cy: number): Vec2[] => {
  const out: Vec2[] = [];
  for (let dy = -1; dy <= 1; dy++) {
    for (let dx = -1; dx <= 1; dx++) {
      if (dx !== 0 || dy !== 0) out.push({ x: cx + dx, y: cy + dy });
    }
  }
  return out;
};

